use crate::ir::*;

pub(super) fn opcode(code: u16) -> Opcode {
    let name = name(code);
    let operation = match code {
        47 => Operation::Data(DataOperation::Record),
        20 => Operation::ControlFlow(ControlFlowOperation::Branch),
        22 => Operation::ControlFlow(ControlFlowOperation::Call),
        23 => Operation::ControlFlow(ControlFlowOperation::Return),
        24 | 140 => Operation::ControlFlow(ControlFlowOperation::Halt),
        28 => Operation::Text(TextOperation::Show),
        30 => Operation::Text(TextOperation::Clear),
        // RetouchSystem::cmdPlayMusic/cmdStopMusic/cmdSetVolume call
        // UxAdvSystem audio methods; cmdEnterFade/Blur/Quake call
        // UxAsyncSubsystem::tmExecFade and UxAdvSystem::enterBlur/quake2.
        50 | 52 | 54 | 56 | 58 | 240 => Operation::Audio(AudioOperation::Play),
        51 | 53 | 55 | 57 | 231 | 241 => Operation::Audio(AudioOperation::Stop),
        59 => Operation::Audio(AudioOperation::SetVolume),
        60 => Operation::Audio(AudioOperation::Wait),
        230 => Operation::Audio(AudioOperation::Control),
        74 | 75 => Operation::Image(ImageOperation::Draw),
        87 => Operation::Effect(EffectOperation::Blur),
        88 => Operation::Effect(EffectOperation::StopBlur),
        105 => Operation::Effect(EffectOperation::Fade),
        106 => Operation::Effect(EffectOperation::StopFade),
        136 => Operation::Effect(EffectOperation::Shake),
        112 | 113 => Operation::Video(VideoOperation::Play),
        114 => Operation::Video(VideoOperation::Stop),
        _ if name.is_some() => Operation::Runtime(RuntimeOperation::EngineCall),
        _ => Operation::Unknown,
    };
    Opcode {
        operation,
        variant: match code {
            47 => Some(Qualifier::Label),
            50 | 51 => Some(Qualifier::Music),
            52 | 53 => Some(Qualifier::Ambient),
            54 | 55 => Some(Qualifier::Looping),
            240 | 241 => Some(Qualifier::AmbientVoice),
            60 => Some(Qualifier::Fade),
            75 => Some(Qualifier::Layer),
            22 | 23 => Some(Qualifier::Conditional),
            _ => None,
        },
        namespace: "exhibit.rld".into(),
        code: u32::from(code),
        native_mnemonic: name.map(str::to_owned),
    }
}

pub(super) fn number_arg(code: u16, variant: u32, i: u32) -> ArgName {
    if i == 0
        && (code == 47
            || (matches!(code, 5 | 20) && variant == 0)
            || (code == 20 && variant == 1)
            || (code == 22 && variant == 0))
    {
        ArgName::LabelId
    } else {
        // cmdSetVolume: kind, channel, volume, duration, flags.
        // cmdStopMusic consumes its first field as fade duration.
        match (code, i) {
            (59, 0) => ArgName::Mode,
            (59, 1) => ArgName::Channel,
            (59, 2) => ArgName::Volume,
            (59, 3) | (51, 0) => ArgName::Duration,
            _ => ArgName::Unknown(u64::from(i)),
        }
    }
}

pub(super) fn string_arg(code: u16, variant: u32, numbers: u32, i: u32) -> ArgName {
    if code == 28 && i == 1 {
        ArgName::Text
    } else if code == 20 && variant == 1 && i == 0 {
        ArgName::Condition
    } else {
        ArgName::Unknown((numbers + i) as u64)
    }
}
